/** Sprite for a hero at a given tier (1-indexed, clamped to the valid range). */
export function getHeroSprite(slug: string, tier: number) {
  const frames = HERO_SPRITES[slug];
  if (!frames) return undefined;
  const clamped = Math.max(1, Math.min(HERO_TIER_COUNT, Math.round(tier)));
  return frames[clamped - 1];
}
